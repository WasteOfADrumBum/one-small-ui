/** `expanded` full width, `collapsed` icon rail, `drawer` below the breakpoint. */
export type SidebarMode = 'expanded' | 'collapsed' | 'drawer';

interface SidebarContextValue {
  id: string;
  collapsed: boolean;
  setCollapsed: (collapsed: boolean) => void;
  mobileOpen: boolean;
  setMobileOpen: (open: boolean) => void;
  mode: SidebarMode;
  drawerBelow: Breakpoint | false;
}
const SidebarContext = createContext<SidebarContextValue | null>(null);

/** Set inside a Sidebar's own markup: whether it shows as a rail, the nesting depth, and the tooltip side. */
interface SidebarPartValue {
  inside: boolean;
  rail: boolean;
  depth: number;
  tipPlacement: 'right' | 'left';
}
const SidebarPartContext = createContext<SidebarPartValue>({ inside: false, rail: false, depth: 0, tipPlacement: 'right' });

export interface SidebarStateProps {
  /** Rail (icons only) on wide screens. Controlled. */
  collapsed?: boolean;
  defaultCollapsed?: boolean;
  onCollapsedChange?: (collapsed: boolean) => void;
  /**
   * Opt-in: remember `collapsed` in `localStorage` under this key. Read after mount, so server and
   * client markup match; storage errors (private mode, blocked storage) are ignored.
   */
  persistKey?: string;
  /** Below this breakpoint the sidebar becomes a Drawer. Default `'lg'`; `false` never. */
  drawerBelow?: Breakpoint | false;
  /** Drawer state below the breakpoint. Controlled. */
  mobileOpen?: boolean;
  defaultMobileOpen?: boolean;
  onMobileOpenChange?: (open: boolean) => void;
  /** id of the sidebar element, which toggles point `aria-controls` at. Generated by default. */
  id?: string;
}

export interface SidebarProviderProps extends SidebarStateProps {
  children?: ReactNode;
}

const readStored = (key: string): boolean | undefined => {
  try {
    const v = window.localStorage.getItem(key);
    return v === 'true' ? true : v === 'false' ? false : undefined;
  } catch {
    return undefined;
  }
};
const writeStored = (key: string, value: boolean) => {
  try {
    window.localStorage.setItem(key, String(value));
  } catch {
    // Storage blocked or full: the state still works for this page view.
  }
};

/**
 * Holds a sidebar's state so a `SidebarToggle` can live anywhere (for example in a `Navbar`).
 * Optional: a `Sidebar` with no provider above creates its own.
 */
export function SidebarProvider({
  collapsed: collapsedProp,
  defaultCollapsed = false,
  onCollapsedChange,
  persistKey,
  drawerBelow = 'lg',
  mobileOpen: mobileOpenProp,
  defaultMobileOpen = false,
  onMobileOpenChange,
  id: idProp,
  children,
}: SidebarProviderProps) {
  const autoId = `os-sidebar-${useId().replace(/:/g, '')}`;
  const id = idProp ?? autoId;
  const [collapsed, setCollapsedRaw] = useControllableState(collapsedProp, defaultCollapsed, onCollapsedChange);
  const [mobileOpen, setMobileOpen] = useControllableState(mobileOpenProp, defaultMobileOpen, onMobileOpenChange);
  const narrow = useMediaQuery(drawerBelow === false ? 'not all' : `(max-width: ${breakpoints[drawerBelow] - 0.02}px)`);
  const collapsedRef = useLatestRef(collapsed);

  const setCollapsed = useCallback(
    (next: boolean) => {
      setCollapsedRaw(next);
      if (persistKey) writeStored(persistKey, next);
    },
    [setCollapsedRaw, persistKey],
  );

  // Restore the remembered state after mount (never during render, so SSR markup matches).
  useEffect(() => {
    if (!persistKey) return;
    const stored = readStored(persistKey);
    if (stored !== undefined && stored !== collapsedRef.current) setCollapsedRaw(stored);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [persistKey]);

  // Growing past the breakpoint removes the drawer: don't leave it "open" for next time.
  useEffect(() => {
    if (!narrow && mobileOpen) setMobileOpen(false);
  }, [narrow, mobileOpen, setMobileOpen]);

  const mode: SidebarMode = narrow ? 'drawer' : collapsed ? 'collapsed' : 'expanded';
  const value = useMemo(
    () => ({ id, collapsed, setCollapsed, mobileOpen, setMobileOpen, mode, drawerBelow }),
    [id, collapsed, setCollapsed, mobileOpen, setMobileOpen, mode, drawerBelow],
  );
  return <SidebarContext.Provider value={value}>{children}</SidebarContext.Provider>;
}

export interface UseSidebarReturn {
  mode: SidebarMode;
  /** The wide-screen preference, kept while the drawer is in use. */
  collapsed: boolean;
  setCollapsed: (collapsed: boolean) => void;
  mobileOpen: boolean;
  setMobileOpen: (open: boolean) => void;
  /** Collapses or expands on wide screens; opens or closes the drawer on narrow ones. */
  toggle: () => void;
  /** id of the sidebar element, for your own `aria-controls`. */
  id: string;
}

/** Reads the nearest Sidebar's state, to build your own toggle or hide content in the rail. */
export function useSidebar(): UseSidebarReturn {
  const ctx = useContext(SidebarContext);
  if (!ctx) throw new Error('useSidebar() must be used inside <Sidebar> or <SidebarProvider>.');
  const { mode, collapsed, setCollapsed, mobileOpen, setMobileOpen, id } = ctx;
  return {
    mode,
    collapsed,
    setCollapsed,
    mobileOpen,
    setMobileOpen,
    id,
    toggle: () => (mode === 'drawer' ? setMobileOpen(!mobileOpen) : setCollapsed(!collapsed)),
  };
}

type SidebarLabelling = { 'aria-label': string; 'aria-labelledby'?: string } | { 'aria-label'?: string; 'aria-labelledby': string };

export type SidebarProps = Omit<HTMLAttributes<HTMLElement>, 'aria-label' | 'aria-labelledby' | 'id'> &
  SidebarStateProps &
  SidebarLabelling & {
    /** Title of the drawer below the breakpoint. Defaults to the `aria-label`. */
    drawerTitle?: ReactNode;
    /** Label of the drawer's close button. Default `'Close navigation'`. */
    closeLabel?: string;
    children?: ReactNode;
  };

/**
 * App navigation in a `<nav>` landmark: expanded, collapsed to an icon rail, and a `Drawer` below
 * `drawerBelow`. Put `SidebarHeader`, `SidebarSection`s and `SidebarFooter` inside.
 */
export const Sidebar = forwardRef<HTMLElement, SidebarProps>(function Sidebar(props, ref) {
  const ctx = useContext(SidebarContext);
  const {
    collapsed,
    defaultCollapsed,
    onCollapsedChange,
    persistKey,
    drawerBelow,
    mobileOpen,
    defaultMobileOpen,
    onMobileOpenChange,
    id,
    ...rest
  } = props;
  if (ctx) return <SidebarRoot ref={ref} {...rest} />;
  return (
    <SidebarProvider
      {...{ collapsed, defaultCollapsed, onCollapsedChange, persistKey, drawerBelow, mobileOpen, defaultMobileOpen, onMobileOpenChange, id }}
    >
      <SidebarRoot ref={ref} {...rest} />
    </SidebarProvider>
  );
});

type SidebarRootProps = Omit<SidebarProps, keyof SidebarStateProps>;

const SidebarRoot = forwardRef<HTMLElement, SidebarRootProps>(function SidebarRoot(
  { drawerTitle, closeLabel = 'Close navigation', className, children, ...rest },
  ref,
) {
  const ctx = useContext(SidebarContext)!;
  const { mode, mobileOpen, setMobileOpen, drawerBelow } = ctx;
  const rail = mode === 'collapsed';
  const navRef = useRef<HTMLElement | null>(null);
  const mergedRef = useMergedRefs(ref, navRef);
  const [rtl, setRtl] = useState(false);
  // The expansion runs on the shared transition engine: `closed` is the rail, `open` full width.
  const { state } = useTransition(!rail, { duration: motion.duration.base });

  useEffect(() => {
    const el = navRef.current;
    if (el) setRtl(getComputedStyle(el).direction === 'rtl');
  }, [mode]);

  const part = useMemo<SidebarPartValue>(
    () => ({ inside: true, rail, depth: 0, tipPlacement: rtl ? 'left' : 'right' }),
    [rail, rtl],
  );

  const items = Children.toArray(children);
  const isType = (el: unknown, type: unknown) => isValidElement(el) && el.type === type;
  const headers = items.filter((el) => isType(el, SidebarHeader));
  const footers = items.filter((el) => isType(el, SidebarFooter));
  const body = items.filter((el) => !isType(el, SidebarHeader) && !isType(el, SidebarFooter));

  const nav = (
    <nav
      ref={mergedRef}
      id={mode === 'drawer' ? undefined : ctx.id}
      className={cx(cls('sidebar'), className)}
      data-mode={mode}
      data-state={state === 'opening' ? 'open' : state}
      data-drawer-below={drawerBelow || undefined}
      {...rest}
    >
      <SidebarPartContext.Provider value={part}>
        {headers}
        <div className={cls('sidebar__body')}>{body}</div>
        {footers}
      </SidebarPartContext.Provider>
    </nav>
  );

  if (mode !== 'drawer') return nav;
  return (
    <Drawer
      id={ctx.id}
      open={mobileOpen}
      onClose={() => setMobileOpen(false)}
      title={drawerTitle ?? rest['aria-label'] ?? 'Navigation'}
      placement="start"
      size="sm"
      closeLabel={closeLabel}
      className={cls('sidebar-drawer')}
    >
      {nav}
    </Drawer>
  );
});

/** Top slot: brand, a `SidebarToggle`, a workspace switcher. Text in `.os-sidebar__label` hides in the rail. */
export const SidebarHeader = forwardRef<HTMLDivElement, HTMLAttributes<HTMLDivElement>>(function SidebarHeader(
  { className, ...rest },
  ref,
) {
  return <div ref={ref} className={cx(cls('sidebar__header'), className)} {...rest} />;
});

/** Bottom slot: account, settings, help. */
export const SidebarFooter = forwardRef<HTMLDivElement, HTMLAttributes<HTMLDivElement>>(function SidebarFooter(
  { className, ...rest },
  ref,
) {
  return <div ref={ref} className={cx(cls('sidebar__footer'), className)} {...rest} />;
});

export interface SidebarSectionProps extends HTMLAttributes<HTMLDivElement> {
  /** A real heading that also names the list (`aria-labelledby`). Visually hidden in the rail. */
  heading?: ReactNode;
  /** Heading level. Default 2. */
  headingLevel?: 2 | 3 | 4 | 5 | 6;
  /** `SidebarItem`s and `SidebarGroup`s. */
  children?: ReactNode;
}

/** A list of items, optionally under a heading. */
export const SidebarSection = forwardRef<HTMLDivElement, SidebarSectionProps>(function SidebarSection(
  { heading, headingLevel = 2, className, children, ...rest },
  ref,
) {
  const headingId = `os-sidebar-heading-${useId().replace(/:/g, '')}`;
  const H = `h${headingLevel}` as 'h2';
  return (
    <div ref={ref} className={cx(cls('sidebar__section'), className)} {...rest}>
      {heading != null && (
        <H id={headingId} className={cls('sidebar__heading')}>
          {heading}
        </H>
      )}
      <ul className={cls('sidebar__list')} aria-labelledby={heading != null ? headingId : undefined}>
        {children}
      </ul>
    </div>
  );
});

/** Props handed to `render` (and to the `as` component). Spread them all onto your link. */
export interface SidebarItemRenderProps {
  /** The item's forwarded ref; typed to fit any element. */
  ref: Ref<never>;
  className: string;
  href?: string;
  'aria-current'?: 'page';
  'aria-disabled'?: 'true';
  'data-active'?: true;
  'data-disabled'?: true;
  type?: 'button';
  onClick: (e: MouseEvent<HTMLElement>) => void;
  children: ReactNode;
  [prop: string]: unknown;
}

export interface SidebarItemProps extends Omit<AnchorHTMLAttributes<HTMLElement>, 'onClick' | 'children'> {
  href?: string;
  /** The current page: sets `aria-current="page"` and the active style. */
  active?: boolean;
  /** Decorative icon; shown alone in the rail. */
  icon?: ReactNode;
  /** A count or status after the label. It is part of the link's name, so keep it short ("3 new"). */
  badge?: ReactNode;
  disabled?: boolean;
  /** Element or component to render, e.g. Next.js `Link`. Default `a` with `href`, else `button`. */
  as?: ElementType;
  /** Full control over the element: receives every prop to spread. Wins over `as`. */
  render?: (props: SidebarItemRenderProps) => ReactElement;
  /** Rail tooltip text when `children` isn't plain text. Default: `children`. */
  tooltip?: ReactNode;
  onClick?: (e: MouseEvent<HTMLElement>) => void;
  children: ReactNode;
}

const abbreviation = (node: ReactNode) => (typeof node === 'string' ? node.trim().charAt(0).toUpperCase() : undefined);

/** A link (with `href` or `as`) or a button in a sidebar. */
export const SidebarItem = forwardRef<HTMLElement, SidebarItemProps>(function SidebarItem(
  { href, active, icon, badge, disabled, as, render, tooltip, onClick, className, children, ...rest },
  ref,
) {
  const ctx = useContext(SidebarContext);
  const part = useContext(SidebarPartContext);
  const isLink = href != null || as != null || render != null;
  const abbr = icon ? undefined : abbreviation(children);

  const content = (
    <>
      {icon ? (
        <span className={cls('sidebar__icon')} aria-hidden="true">
          {icon}
        </span>
      ) : (
        abbr && (
          <span className={cls('sidebar__abbr')} aria-hidden="true">
            {abbr}
          </span>
        )
      )}
      <span className={cls('sidebar__label')}>{children}</span>
      {badge != null && <span className={cls('sidebar__badge')}>{badge}</span>}
    </>
  );

  const handleClick = (e: MouseEvent<HTMLElement>) => {
    if (disabled) {
      e.preventDefault();
      return;
    }
    onClick?.(e);
    if (!e.defaultPrevented && isLink && ctx?.mode === 'drawer') ctx.setMobileOpen(false);
  };

  const shared = {
    ...rest,
    className: cx(cls('sidebar__link'), className),
    'data-active': active || undefined,
    'data-disabled': disabled || undefined,
    onClick: handleClick,
  };

  let el: ReactElement<Record<string, unknown>>;
  if (disabled) {
    el = (
      <a {...(shared as AnchorHTMLAttributes<HTMLAnchorElement>)} ref={ref as Ref<HTMLAnchorElement>} aria-disabled="true">
        {content}
      </a>
    );
  } else {
    const Tag: ElementType = as ?? (href != null ? 'a' : 'button');
    const props = {
      ...shared,
      href,
      'aria-current': active ? ('page' as const) : undefined,
      type: Tag === 'button' ? ('button' as const) : undefined,
    };
    el = render ? (
      // The ref is only passed through for the caller to spread onto its element, never read here.
      // eslint-disable-next-line react-hooks/refs
      (render({ ...props, ref, children: content } as SidebarItemRenderProps) as ReactElement<Record<string, unknown>>)
    ) : (
      <Tag ref={ref} {...props}>
        {content}
      </Tag>
    );
  }

  return (
    <li className={cls('sidebar__item')}>
      <Tooltip
        content={tooltip ?? children}
        placement={part.tipPlacement}
        describe={false}
        open={part.rail && part.depth === 0 ? undefined : false}
        className={cls('sidebar__tip')}
      >
        {el}
      </Tooltip>
    </li>
  );
});

export interface SidebarGroupProps extends Omit<ButtonHTMLAttributes<HTMLButtonElement>, 'children'> {
  label: ReactNode;
  icon?: ReactNode;
  /** Highlights the trigger. Default: when a direct child item is `active`. */
  active?: boolean;
  open?: boolean;
  /** Default: open when a direct child item is `active`. */
  defaultOpen?: boolean;
  onOpenChange?: (open: boolean) => void;
  /** Rail tooltip text when `label` isn't plain text. */
  tooltip?: ReactNode;
  /** Nested `SidebarItem`s. */
  children?: ReactNode;
}

/**
 * A disclosure: a button with `aria-expanded` that shows nested items. In the rail, activating it
 * expands the sidebar and opens the group.
 */
export const SidebarGroup = forwardRef<HTMLButtonElement, SidebarGroupProps>(function SidebarGroup(
  { label, icon, active, open: openProp, defaultOpen, onOpenChange, tooltip, onClick, className, children, ...rest },
  ref,
) {
  const ctx = useContext(SidebarContext);
  const part = useContext(SidebarPartContext);
  const panelId = `os-sidebar-group-${useId().replace(/:/g, '')}`;
  const hasActive = Children.toArray(children).some((c) => isValidElement<{ active?: boolean }>(c) && c.props.active);
  const [open, setOpen] = useControllableState(openProp, defaultOpen ?? hasActive, onOpenChange);
  const shown = open && !part.rail;
  const abbr = icon ? undefined : abbreviation(label);
  const nested = useMemo(() => ({ ...part, depth: part.depth + 1 }), [part]);

  return (
    <li className={cx(cls('sidebar__item'), cls('sidebar__group'))}>
      <Tooltip
        content={tooltip ?? label}
        placement={part.tipPlacement}
        describe={false}
        open={part.rail && part.depth === 0 ? undefined : false}
        className={cls('sidebar__tip')}
      >
        <button
          ref={ref}
          type="button"
          className={cx(cls('sidebar__link'), cls('sidebar__group-trigger'), className)}
          aria-expanded={shown}
          aria-controls={panelId}
          data-active={(active ?? hasActive) || undefined}
          onClick={(e) => {
            onClick?.(e);
            if (e.defaultPrevented) return;
            if (part.rail && ctx) {
              ctx.setCollapsed(false);
              if (!open) setOpen(true);
            } else setOpen(!open);
          }}
          {...rest}
        >
          {icon ? (
            <span className={cls('sidebar__icon')} aria-hidden="true">
              {icon}
            </span>
          ) : (
            abbr && (
              <span className={cls('sidebar__abbr')} aria-hidden="true">
                {abbr}
              </span>
            )
          )}
          <span className={cls('sidebar__label')}>{label}</span>
          <ChevronDownIcon className={cls('sidebar__chevron')} />
        </button>
      </Tooltip>
      <Collapse id={panelId} open={shown} className={cls('sidebar__panel')}>
        <SidebarPartContext.Provider value={nested}>
          <ul className={cls('sidebar__list')} data-nested="">
            {children}
          </ul>
        </SidebarPartContext.Provider>
      </Collapse>
    </li>
  );
});

export interface SidebarToggleLabels {
  /** Wide screen, sidebar expanded. Default `'Collapse sidebar'`. */
  collapse: string;
  /** Wide screen, rail. Default `'Expand sidebar'`. */
  expand: string;
  /** Narrow screen, drawer closed. Default `'Open navigation'`. */
  open: string;
}

const defaultToggleLabels: SidebarToggleLabels = {
  collapse: 'Collapse sidebar',
  expand: 'Expand sidebar',
  open: 'Open navigation',
};

export interface SidebarToggleProps extends Omit<ButtonHTMLAttributes<HTMLButtonElement>, 'color' | 'children'> {
  labels?: Partial<SidebarToggleLabels>;
  variant?: ButtonVariant;
  color?: Color;
  size?: ExtendedSize;
  /** Replaces the default icon. */
  children?: ReactNode;
}

/**
 * Collapses and expands the sidebar on wide screens and opens the drawer on narrow ones, with
 * `aria-expanded` and `aria-controls`. Works inside the sidebar or anywhere under a `SidebarProvider`.
 * Inside the drawer it renders nothing: the drawer has its own close button.
 */
export const SidebarToggle = forwardRef<HTMLButtonElement, SidebarToggleProps>(function SidebarToggle(
  { labels, variant = 'ghost', color = 'neutral', size, onClick, className, children, ...rest },
  ref,
) {
  const ctx = useContext(SidebarContext);
  const part = useContext(SidebarPartContext);
  if (!ctx) throw new Error('<SidebarToggle> must be inside <Sidebar> or <SidebarProvider>.');
  const { mode, collapsed, setCollapsed, mobileOpen, setMobileOpen, id } = ctx;
  if (part.inside && mode === 'drawer') return null;
  const l = { ...defaultToggleLabels, ...labels };
  const drawer = mode === 'drawer';
  return (
    <Button
      ref={ref as never}
      variant={variant}
      color={color}
      size={size}
      iconOnly
      className={cx(cls('sidebar-toggle'), className)}
      data-mode={mode}
      aria-label={drawer ? l.open : collapsed ? l.expand : l.collapse}
      aria-expanded={drawer ? mobileOpen : !collapsed}
      aria-controls={id}
      onClick={(e) => {
        onClick?.(e);
        if (e.defaultPrevented) return;
        if (drawer) setMobileOpen(!mobileOpen);
        else setCollapsed(!collapsed);
      }}
      {...rest}
    >
      {children ?? (drawer ? <MenuIcon /> : <ChevronLeftIcon />)}
    </Button>
  );
});
