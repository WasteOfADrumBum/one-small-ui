// Generates the SCSS theme maps, the SCSS motion maps and the TypeScript token
// module from tokens/themes.json, so tokens have a single source of truth.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { readTokens } from './tokens-lib.mjs';

const pkg = fileURLToPath(new URL('../packages/onesmallui/', import.meta.url));
const { themes, motion } = readTokens();
const banner = '// AUTO-GENERATED by scripts/build-tokens.mjs from tokens/themes.json. Do not edit.\n';

const scssMap = (name, t, unit = '') =>
  `$${name}: (\n${Object.entries(t)
    .map(([k, v]) => `  '${k}': ${v}${unit},`)
    .join('\n')}\n) !default;\n`;

writeFileSync(
  `${pkg}scss/abstracts/_themes.scss`,
  banner + '\n' + Object.entries(themes).map(([n, t]) => scssMap(`theme-${n}`, t)).join('\n'),
);

writeFileSync(
  `${pkg}scss/abstracts/_motion.scss`,
  banner + '\n' + scssMap('motion-durations', motion.duration, 'ms') + '\n' + scssMap('motion-easings', motion.easing),
);

writeFileSync(
  `${pkg}src/tokens.ts`,
  banner +
    '\n/** Theme color tokens. Each key is exposed as a CSS custom property `--os-<key>`. */\n' +
    `export const themes = ${JSON.stringify(themes, null, 2)} as const;\n\n` +
    'export type ThemeName = keyof typeof themes;\n' +
    'export type ColorToken = keyof (typeof themes)["light"];\n\n' +
    '/** Returns a `var(--os-*)` reference for a color token. */\n' +
    'export const cssVar = (token: ColorToken): string => `var(--os-${token})`;\n\n' +
    '/**\n * Motion tokens: durations in ms (`--os-duration-<key>`) and easings (`--os-ease-<key>`).\n' +
    ' * Durations collapse to ~0 under reduced motion.\n */\n' +
    `export const motion = ${JSON.stringify(motion, null, 2)} as const;\n\n` +
    'export type MotionDuration = keyof (typeof motion)["duration"];\n' +
    'export type MotionEasing = keyof (typeof motion)["easing"];\n',
);
console.log('Tokens generated.');
